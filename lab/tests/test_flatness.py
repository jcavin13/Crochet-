import math

import pytest

from conftest import ALL, fixture_pattern
from crolab import builders as B
from crolab import graph as G
from crolab.flatness import analyse


@pytest.mark.parametrize("name", ALL)
@pytest.mark.parametrize("source", ["fixture", "builder"])
def test_analytic_flatness(name, source):
    p = fixture_pattern(name)[0] if source == "fixture" else B.builder_for_fixture(name, include_lace=True)
    exp = G.load_expected(name)["analytic"]
    fl = analyse(p)
    rows = [r for r in fl["rounds"] if r["class"] != "n/a"]
    assert fl["final"] == exp["final"]
    if "rounds" in exp:
        assert len(rows) == len(exp["rounds"])
        for got, want in zip(rows, exp["rounds"]):
            assert got["class"] == want["class"], (got["label"], got, want)
            assert got["e"] == pytest.approx(want["excess"], abs=0.01)
            if want["class"] != "flat":
                assert got["stitches_off"] == pytest.approx(want["stitches_off"], abs=0.15)
    else:  # lace: every round flat
        assert all(r["class"] == "flat" for r in rows), [(r["label"], r["e_min"], r["e_max"]) for r in rows]


def test_rows_not_applicable():
    fl = analyse(B.rect_rows("sc", 10, 5))
    assert not fl["applicable"] and all(r["class"] == "n/a" for r in fl["rounds"])


def test_messages_and_g():
    fl = analyse(B.builder_for_fixture("hyperbolic_plane"))
    r3 = fl["rounds"][2]
    assert r3["message"].startswith("Rnd 3 will ruffle: about 6 stitches over flat (+")
    assert math.isnan(fl["rounds"][0]["g"])
    tube = analyse(B.sc_rounds([6, 12, 18, 18, 18]))["rounds"]
    assert tube[3]["g"] == pytest.approx(-1.0)


@pytest.mark.parametrize("name", ALL)
def test_flatness_matches_typescript_golden(name):
    """Cross-language pin of the flatness formula (docs/review.md R8). The golden file
    `spec/fixtures/<name>.flatness.json` is written by the TypeScript analyzer from the compiled
    graph; shape {"name", "rounds": [{"round", "class", "e_min", "e_max", "e", "rho", "r"}]} with
    floats rounded to 6 decimals. Skipped until the app side generates it."""
    import json

    from crolab import FIXTURES_DIR
    from crolab.compare import json_diff
    from crolab.flatness import golden_record

    path = FIXTURES_DIR / f"{name}.flatness.json"
    if not path.exists():
        pytest.skip(f"no {path.name} (generated by the app's fixtures script)")
    if not G.fixture_graph_path(name).exists():
        pytest.skip("no compiled graph")
    ref = json.loads(path.read_text(encoding="utf-8"))
    got = golden_record(name, G.load(G.fixture_graph_path(name)))
    assert ref["name"] == name
    by_round = {r["round"]: r for r in got["rounds"]}
    assert [r["round"] for r in ref["rounds"]] == sorted(by_round), "round list differs"
    diffs = []
    for want in ref["rounds"]:
        have = {k: by_round[want["round"]][k] for k in want}   # compare the fields the file has
        diffs += json_diff(have, want, rel=1e-9, abs_=2e-6, path=f"round {want['round']}")
    assert not diffs, "; ".join(diffs[:8])


def test_golden_record_shape():
    from crolab.flatness import golden_record
    rec = golden_record("sc_cone", B.builder_for_fixture("sc_cone"))
    assert rec["name"] == "sc_cone" and len(rec["rounds"]) == 8
    assert set(rec["rounds"][0]) == {"round", "class", "e_min", "e_max", "e", "rho", "r"}

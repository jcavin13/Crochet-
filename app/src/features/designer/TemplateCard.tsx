// A printable blocking template: preview, "Download SVG" and "Print at 100 %".
import { useMemo } from 'react';
import { Button, Icon, toast } from '@/ui';
import { PrintIcon } from './icons';

const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'template';

export function downloadSvg(svg: string, name: string) {
  const blob = new Blob([svg], { type: 'image/svg+xml' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url; a.download = `${slug(name)}-blocking-template.svg`;
  document.body.appendChild(a); a.click(); a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}

/** Print the SVG on its own page at actual size (a hidden iframe, so nothing else is printed). */
export function printSvg(svg: string, title: string) {
  const f = document.createElement('iframe');
  f.style.position = 'fixed'; f.style.right = '0'; f.style.bottom = '0'; f.style.width = '0'; f.style.height = '0'; f.style.border = '0';
  f.setAttribute('aria-hidden', 'true');
  document.body.appendChild(f);
  const doc = f.contentDocument;
  if (!doc || !f.contentWindow) { f.remove(); toast('Printing is not available here — download the SVG instead', { tone: 'error' }); return; }
  doc.open();
  doc.write(`<!doctype html><html><head><meta charset="utf-8"><title>${title.replace(/</g, '&lt;')}</title><style>@page{margin:8mm}html,body{margin:0;background:#fff}svg{display:block}</style></head><body>${svg}</body></html>`);
  doc.close();
  setTimeout(() => { try { f.contentWindow!.focus(); f.contentWindow!.print(); } finally { setTimeout(() => f.remove(), 1000); } }, 100);
}

export function TemplateCard({ svg, title, note }: { svg: string; title: string; note?: string }) {
  const html = useMemo(() => ({ __html: svg }), [svg]);
  return (
    <div className="dz-template">
      <div className="dz-template__bar">
        <span className="small muted">{note ?? 'Pin-out guide at actual size. Print at 100 % (no "fit to page"); the scale bar must measure 5 cm.'}</span>
        <span className="spacer" />
        <Button size="sm" onClick={() => downloadSvg(svg, title)}><Icon name="download" size={16} />Download SVG</Button>
        <Button size="sm" variant="primary" onClick={() => printSvg(svg, title)}><PrintIcon size={16} />Print</Button>
      </div>
      {/* the SVG is generated by core/generate/snowflake/template.ts from numbers only (text is escaped) */}
      <div className="dz-template__svg" dangerouslySetInnerHTML={html} />
    </div>
  );
}

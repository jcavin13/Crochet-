import { describe, expect, it } from 'vitest';
import { compilePattern } from '../../notation';
import { estimateYarn } from '../../yarn';
import { paramSetById } from '../../params';
import { analyzeSymmetry } from '../../symmetry';
import {
  generateSnowflake, randomSnowflake, mutateSnowflake, snowflakeVariations, SNOWFLAKE_PRESETS, snowflakeTemplateSvg, branchPairs,
  type SnowflakeResult, type SnowflakeSpec, type TipStyle, type SnowCentreStyle, type SnowBodyMotif, type MinorStyle,
} from './index';

const THREAD = paramSetById('thread-10_1.5mm')!;
const WORSTED = paramSetById('worsted-4_5.0mm')!;

let symChecked = 0;
/** Everything a generated snowflake must satisfy. */
function expectValid(r: SnowflakeResult, where: string, { bodyFlat = true } = {}) {
  expect(r.diagnostics, `${where}\n${r.text}`).toEqual([]);
  const res = compilePattern(r.text);
  expect(res.diagnostics.filter((d) => d.severity !== 'info').map((d) => d.message), `${where}\n${r.text}`).toEqual([]);
  const g = res.pattern!.graph;
  const n = r.spec.points;
  expect(g.rounds.length).toBe(r.rounds.length);
  g.rounds.forEach((round, i) => {
    expect(round.stitchCount % n, `${where} ${round.label} stitches`).toBe(0);
    expect(g.spaces.filter((s) => s.kind === 'chsp' && s.round === i).length % n, `${where} ${round.label} spaces`).toBe(0);
    expect(round.declaredCount, `${where} ${round.label} has a count`).toBeDefined();
    expect(round.declaredCount).toBe(round.stitchCount);
    expect(r.rounds[i].stitches).toBe(round.stitchCount);
    expect(round.joined).toBe(true);
  });
  const sym = analyzeSymmetry(g);
  if (sym.applicable) { expect(sym.order % n, `${where} symmetry ${sym.group}`).toBe(0); symChecked++; }
  if (bodyFlat) for (const x of r.rounds.filter((x) => x.kind !== 'arms')) expect(x.class, `${where} ${x.message}`).toBe('flat');
  expect(r.rounds[r.rounds.length - 1].class).toBe('pointed');
  // blocked outline numbers are sane
  expect(r.shape.tipR).toBeGreaterThan(r.shape.valleyR);
  expect(r.shape.valleyR).toBeGreaterThan(r.shape.bodyR * 0.98);
  expect(r.shape.bodyR).toBeGreaterThan(0);
  // header contract
  expect(r.text).toMatch(/^source: generated by the snowflake designer \(/m);
  expect(r.text).toMatch(/^license: CC0-1.0$/m);
  expect(r.text).toMatch(/^params: /m);
  expect(r.text).toMatch(/^yarn: /m);
}

/** Branch pins per point predicted from the spec: two per branch pair, two trefoil side picots. */
const branchPinsPerPoint = (s: SnowflakeSpec) => 2 * branchPairs(s.arm) + (s.arm.tip === 'trefoil' ? 2 : 0);

describe('snowflake property test: seeds × points × styles', () => {
  const stats = { total: 0, crisp: 0, bodyRounds: 0, flatBody: 0, inSize: 0, sizes: [] as number[] };
  for (const points of [5, 6, 8, 12]) {
    it(`${points} points`, () => {
      for (let s = 0; s < 24; s++) {
        const seed = 5000 + points * 100 + s;
        const c = { points, bold: (s % 3) / 2, spiky: (s % 4) / 3, ornate: (s % 5) / 4, rounds: (s % 2 ? [2, 4] : [4, 7]) as [number, number], sizeCm: [6, 10] as [number, number] };
        const spec = randomSnowflake(seed, c);
        expect(randomSnowflake(seed, c), 'deterministic').toEqual(spec);
        const params = s % 7 === 6 ? WORSTED : THREAD;
        const r = generateSnowflake(spec, params);
        expectValid(r, `seed ${seed} n=${points}`);
        expect(generateSnowflake(spec, params).text).toBe(r.text);
        expect(r.text).toContain(`(seed ${seed}, ${points} points)`);
        stats.total++;
        if (r.check.ok) stats.crisp++;
        const body = r.rounds.filter((x) => x.kind !== 'arms');
        stats.bodyRounds += body.length; stats.flatBody += body.filter((x) => x.class === 'flat').length;
        if (params === THREAD) { stats.sizes.push(r.stats.diameterMm / 10); if (r.stats.diameterMm >= 60 && r.stats.diameterMm <= 100) stats.inSize++; }
        // the template: n guide lines, one pin mark per predicted pin
        const svg = snowflakeTemplateSvg(r);
        expect(svg.match(/class="guide"/g)?.length).toBe(points);
        expect(svg.match(/class="pin"/g)?.length).toBe(r.shape.pins.length);
        expect(r.shape.pins.length % points).toBe(0);
        expect(r.shape.pins.filter((p) => p.kind === 'tip').length).toBe(points);
        expect(r.shape.pins.filter((p) => p.kind === 'branch').length).toBe(points * branchPinsPerPoint(r.spec));
      }
    }, 60_000);
  }
  it('summary', () => {
    const thread = stats.sizes.length;
    console.log(`[snowflake] ${stats.total} random snowflakes: ${stats.crisp} pass the snowflake check (${((stats.crisp / stats.total) * 100).toFixed(1)} %), `
      + `${stats.flatBody}/${stats.bodyRounds} body rounds flat; thread size across points ${Math.min(...stats.sizes).toFixed(1)}–${Math.max(...stats.sizes).toFixed(1)} cm, `
      + `${stats.inSize}/${thread} within 6–10 cm; symmetry checked on ${symChecked}`);
    expect(stats.total).toBe(96);
    expect(stats.flatBody).toBe(stats.bodyRounds);
    expect(stats.crisp / stats.total).toBeGreaterThanOrEqual(0.95);
    expect(stats.inSize / thread).toBeGreaterThanOrEqual(0.9);
  });
});

describe('every arm motif × centre × body', () => {
  const tips: TipStyle[] = ['picot', 'trefoil', 'spike', 'bobble', 'loop'];
  const centres: SnowCentreStyle[] = ['ring', 'spoked', 'double-spoked', 'cluster', 'petal'];
  const bodies: (SnowBodyMotif | null)[] = [null, 'hexagon', 'corners', 'major-minor'];
  const minors: MinorStyle[] = ['none', 'picot', 'spike', 'trefoil'];
  let total = 0, flat = 0, crisp = 0;
  for (const tip of tips) {
    it(`${tip} tips`, () => {
      centres.forEach((centre, ci) => bodies.forEach((body, bi) => {
        for (const points of [6, 8]) {
          const spec: SnowflakeSpec = {
            points, centre: { style: centre }, body: body ? [{ motif: 'hexagon' }, { motif: body }] : [],
            arm: { length: 9, branches: (ci + bi) % 3, picot: 3 + (bi % 2), tip, back: (ci + bi) % 2 ? 'sc' : 'slst', graded: bi === 2 },
            minor: { style: minors[(ci + bi) % 4], length: 3, picot: 3 }, valley: { depth: (['deep', 'medium', 'shallow'] as const)[ci % 3], anchor: bi % 2 === 1 },
          };
          const r = generateSnowflake(spec, THREAD);
          expectValid(r, `${tip} ${centre} ${body} n=${points}`, { bodyFlat: false });
          total++;
          if (r.rounds.filter((x) => x.kind !== 'arms').every((x) => x.class === 'flat')) flat++;
          if (r.check.ok) crisp++;
        }
      }));
    }, 60_000);
  }
  it('body rounds are flat in nearly every combination', () => {
    console.log(`[snowflake] combinations: ${flat}/${total} with a flat body, ${crisp}/${total} pass the whole check`);
    expect(total).toBe(tips.length * centres.length * bodies.length * 2);
    expect(flat / total).toBeGreaterThanOrEqual(0.97);
  });
});

describe('snowflake generator details', () => {
  it('presets compile, lie flat in the body and block to a crisp star', () => {
    for (const p of SNOWFLAKE_PRESETS) {
      const r = generateSnowflake(p.spec, THREAD);
      expectValid(r, p.id);
      expect(r.check.ok, `${p.id}: ${r.check.summary}`).toBe(true);
      expect(r.warnings, p.id).toEqual([]);
      expect(r.text).toMatch(/^source: generated by the snowflake designer \(guided, \d+ points\)$/m);
    }
  });

  it('arms are worked into the loop they start from (the closing sc goes back into it)', () => {
    const r = generateSnowflake(SNOWFLAKE_PRESETS.find((p) => p.id === 'fern')!.spec, THREAD);
    const g = r.pattern!.graph;
    const last = g.rounds.length - 1;
    const scs = g.nodes.filter((n) => n.round === last && n.type === 'sc' && n.into.some((a) => 'space' in a));
    // two sc into each point's loop (before and after the arm)
    const bySpace = new Map<number, number>();
    for (const s of scs) for (const a of s.into) if ('space' in a) bySpace.set(a.space, (bySpace.get(a.space) ?? 0) + 1);
    expect([...bySpace.values()].filter((v) => v === 2).length).toBe(6);
    expect(r.text).toMatch(/\(sc, ch \d+, sl st in 4th ch from hook, .*sc\) in next ch-\d+ sp/);
  });

  it('UK terms compile to the same graph', () => {
    for (const p of SNOWFLAKE_PRESETS) {
      const us = generateSnowflake({ ...p.spec, terms: 'US' }, THREAD);
      const uk = generateSnowflake({ ...p.spec, terms: 'UK' }, THREAD);
      expectValid(uk, `${p.id} UK`);
      const strip = (x: SnowflakeResult) => x.pattern!.graph.nodes.map((nd) => `${nd.type}:${JSON.stringify(nd.into)}`).join(' ');
      expect(strip(uk)).toBe(strip(us));
    }
  });

  it('flags bridges that pull tight or sag, and branches that collide', () => {
    const base = SNOWFLAKE_PRESETS[0].spec;
    const tight = generateSnowflake({ ...base, valley: { depth: 'medium', anchor: false, chains: 1 } }, THREAD);
    expect(tight.check.ok).toBe(false);
    expect(tight.check.items.find((i) => i.id === 'web')!.text).toMatch(/too short/);
    const sag = generateSnowflake({ ...base, valley: { depth: 'medium', anchor: false, chains: 40 } }, THREAD);
    expect(sag.check.items.find((i) => i.id === 'web')!.text).toMatch(/sag/);
    const crowded = generateSnowflake({ ...base, points: 12, body: [], arm: { length: 8, branches: 3, picot: 6, tip: 'trefoil', back: 'slst' } }, THREAD);
    expect(crowded.check.items.find((i) => i.id === 'clearance')!.ok).toBe(false);
    const stubby = generateSnowflake({ ...base, arm: { ...base.arm, length: 3, tip: 'picot', picot: 3 }, valley: { depth: 'shallow', anchor: false } }, THREAD);
    expect(stubby.check.items.find((i) => i.id === 'shape')!.ok).toBe(false);
  });

  it('size targeting: the across-points diameter lands in the wanted range', () => {
    for (const [lo, hi] of [[5, 7], [8, 10], [10, 12]] as [number, number][]) {
      let inRange = 0;
      for (let seed = 1; seed <= 8; seed++) {
        const r = generateSnowflake(randomSnowflake(seed, { sizeCm: [lo, hi] }), THREAD);
        if (r.stats.diameterMm / 10 >= lo - 0.3 && r.stats.diameterMm / 10 <= hi + 0.3) inRange++;
      }
      expect(inRange, `${lo}–${hi} cm`).toBeGreaterThanOrEqual(7);
    }
  });

  it('variations and "more like this" are deterministic and different', () => {
    const a = snowflakeVariations(3, 12), b = snowflakeVariations(3, 12);
    expect(a).toEqual(b);
    expect(new Set(a.map((s) => JSON.stringify({ ...s, seed: 0 }))).size).toBeGreaterThanOrEqual(10);
    const base = a[0];
    const m1 = mutateSnowflake(base, 11), m2 = mutateSnowflake(base, 11);
    expect(m1).toEqual(m2);
    expect(JSON.stringify({ ...m1, seed: 0 })).not.toBe(JSON.stringify({ ...base, seed: 0 }));
    expectValid(generateSnowflake(m1, THREAD), 'mutation');
  });

  it('stats are plausible for thread', () => {
    const r = generateSnowflake(SNOWFLAKE_PRESETS[0].spec, THREAD);
    expect(r.stats.rounds).toBe(3);
    expect(r.stats.diameterMm / 10).toBeGreaterThan(4);
    expect(r.stats.diameterMm / 10).toBeLessThan(12);
    expect(r.stats.threadM).toBeGreaterThan(0.5);
    // core/yarn's nominal estimate (net), the same figure the thread panel starts from
    const est = estimateYarn(r.pattern!, THREAD);
    expect(r.stats.threadM).toBeCloseTo(est.net.meters, 9);
    expect(r.stats.threadG).toBeCloseTo(est.net.grams!, 9);
    expect(r.check.summary).toMatch(/^Blocks to a crisp star: tip radius \d+\.\d cm, valley radius \d+\.\d cm, .* clear each other by/);
  });
});

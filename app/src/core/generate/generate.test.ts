import { describe, expect, it } from 'vitest';
import { compilePattern } from '../notation';
import { analyzeFlatness } from '../flatness';
import { paramSetById, paramsFile } from '../params';
import {
  generateDoily, MOTIFS, MOTIF_ORDER, PRESETS, randomSpec, type DoilySpec, type GenerateResult, type MotifId, type RoundSpec,
} from './index';
import { planDoily } from './generate';

const THREAD = paramSetById('thread-10_1.5mm')!;
const WORSTED = paramSetById('worsted-4_5.0mm')!;

/** Everything a generated pattern must satisfy, whatever its shape. */
function expectValid(r: GenerateResult, spec: DoilySpec, where: string) {
  expect(r.diagnostics, `${where}\n${r.text}`).toEqual([]);
  const res = compilePattern(r.text);
  const problems = res.diagnostics.filter((d) => d.severity !== 'info');
  expect(problems.map((d) => d.message), where).toEqual([]);
  expect(res.pattern, where).toBeDefined();
  const n = spec.symmetry;
  const g = res.pattern!.graph;
  expect(g.rounds.length).toBe(r.rounds.length);
  g.rounds.forEach((round, i) => {
    // n-fold symmetry: stitches and spaces of every round come in multiples of n
    expect(round.stitchCount % n, `${where} ${round.label} stitches`).toBe(0);
    const spaces = g.spaces.filter((s) => s.kind === 'chsp' && s.round === i).length;
    expect(spaces % n, `${where} ${round.label} spaces`).toBe(0);
    // the generator's own bookkeeping agrees with the compiler
    expect(r.rounds[i].stitches).toBe(round.stitchCount);
    expect(r.rounds[i].spaces).toBe(spaces);
    if (round.declaredCount !== undefined) expect(round.declaredCount).toBe(round.stitchCount);
    expect(r.rounds[i].text).toMatch(/\)\s*$/); // every round carries a count annotation
    expect(round.joined).toBe(true);
  });
  // header contract
  expect(r.text).toMatch(/^title: .+$/m);
  expect(r.text).toMatch(/^terms: (US|UK)$/m);
  expect(r.text).toMatch(/^params: /m);
  expect(r.text).toMatch(/^source: generated by the designer \(/m);
  expect(r.text).toMatch(/^license: CC0-1.0$/m);
}

describe('property: random designs over seeds × symmetry 4–24 × constraints', () => {
  const failures: string[] = [];
  let total = 0, allFlat = 0, rounds = 0, flatRounds = 0;
  const orders = Array.from({ length: 21 }, (_, i) => i + 4);
  for (const n of orders) {
    it(`symmetry ${n}`, () => {
      for (let s = 0; s < 14; s++) {
        const seed = 1000 * n + s;
        const constraints = {
          symmetry: n,
          rounds: (s % 3 === 0 ? [4, 7] : s % 3 === 1 ? [7, 11] : [10, 14]) as [number, number],
          lacy: (s % 5) / 4,
          heights: s % 4 === 3 ? (['sc', 'dc'] as const).slice() : undefined,
        };
        // raw: the grammar's first draw, so this measures the solver, not the sampler's filter
        const spec = randomSpec(seed, constraints, { raw: true });
        const params = s % 2 ? THREAD : WORSTED;
        const r = generateDoily(spec, params);
        expectValid(r, spec, `seed ${seed} n=${n}`);
        total++;
        const bad = r.rounds.filter((x) => x.class !== 'flat');
        rounds += r.rounds.length; flatRounds += r.rounds.length - bad.length;
        if (!bad.length) allFlat++;
        else failures.push(`seed ${seed} n=${n}: ${bad.map((b) => `${b.motif} ${b.message}`).join('; ')}`);
      }
    }, 60_000);
  }
  it('flat in every round for ≥ 95 % of designs (target flat)', () => {
    const rate = allFlat / total;
    console.log(`[generate] raw grammar draws: ${allFlat}/${total} designs flat in every round (${(rate * 100).toFixed(1)} %), `
      + `${flatRounds}/${rounds} rounds flat (${((flatRounds / rounds) * 100).toFixed(2)} %)`);
    if (failures.length) console.log('[generate] non-flat cases:\n  ' + failures.join('\n  '));
    expect(total).toBe(orders.length * 14);
    expect(rate).toBeGreaterThanOrEqual(0.95);
  });
});

describe('surprise me (filtered sampler)', () => {
  it('always flat for a range of seeds and is deterministic', () => {
    let flat = 0;
    const N = 40;
    for (let seed = 1; seed <= N; seed++) {
      const c = { symmetry: [5, 16] as [number, number], rounds: [6, 10] as [number, number], lacy: 0.6, params: THREAD };
      const spec = randomSpec(seed, c);
      expect(randomSpec(seed, c)).toEqual(spec);
      const r = generateDoily(spec, THREAD);
      expectValid(r, spec, `seed ${seed}`);
      if (r.rounds.every((x) => x.class === 'flat')) flat++;
      expect(generateDoily(spec, THREAD).text).toBe(r.text);
    }
    console.log(`[generate] filtered sampler: ${flat}/${N} flat`);
    expect(flat).toBe(N);
  }, 60_000);

  it('respects round-count and diameter constraints', () => {
    for (let seed = 1; seed <= 10; seed++) {
      const spec = randomSpec(seed, { symmetry: 8, rounds: [6, 8], diameterCm: [14, 22], params: WORSTED });
      expect(spec.rounds.length).toBeGreaterThanOrEqual(6);
      expect(spec.rounds.length).toBeLessThanOrEqual(8);
      const r = generateDoily(spec, WORSTED);
      expect(r.stats.diameterMm / 10).toBeGreaterThan(14 - 3);
      expect(r.stats.diameterMm / 10).toBeLessThan(22 + 3);
    }
  }, 60_000);

  it('the seed is recorded in the header', () => {
    const r = generateDoily(randomSpec(1234, { symmetry: 10 }), THREAD);
    expect(r.text).toMatch(/source: generated by the designer \(seed 1234, 10-fold\)/);
  });
});

describe('target shapes', () => {
  const bodies: RoundSpec[][] = [
    [{ motif: 'centre' }, { motif: 'spokes' }, { motif: 'mesh' }, { motif: 'shells' }, { motif: 'mesh' }, { motif: 'shells' }, { motif: 'fans' }],
    [{ motif: 'centre', params: { st: 'sc' } }, { motif: 'solid' }, { motif: 'solid' }, { motif: 'solid' }, { motif: 'solid' }, { motif: 'solid' }],
    [{ motif: 'centre' }, { motif: 'clusters' }, { motif: 'mesh' }, { motif: 'vstitch' }, { motif: 'solid' }, { motif: 'picot' }],
  ];
  for (const shape of ['ruffle', 'bowl'] as const) {
    for (const n of [6, 8, 12]) {
      bodies.forEach((rounds, bi) => {
        it(`${shape} n=${n} body ${bi}`, () => {
          const spec: DoilySpec = { symmetry: n, rounds, target: { shape, rounds: 2, amount: 0.15 } };
          const r = generateDoily(spec, THREAD);
          expectValid(r, spec, `${shape} ${n} ${bi}`);
          const want = shape === 'ruffle' ? 'ruffle' : 'cup';
          const last2 = r.rounds.slice(-2);
          for (const x of last2) expect(x.class, x.message).toBe(want);
          for (const x of r.rounds.slice(0, -2)) expect(x.class, x.message).toBe('flat');
        });
      });
    }
  }
});

describe('every motif on every interface', () => {
  // predecessors chosen to leave each kind of interface: solid (plain, mixed scallop, accents),
  // lace with one space (mesh, spokes, clusters, puffs), two spaces (V, open shells, petals,
  // alternating shells), picot edge, and the spoked centre
  const preds: RoundSpec[] = [
    { motif: 'solid', params: { st: 'dc' } }, { motif: 'solid', params: { st: 'sc' } },
    { motif: 'accent', params: { kind: 'pc' } }, { motif: 'accent', params: { kind: 'puff' } }, { motif: 'accent', params: { kind: 'bobble' } },
    { motif: 'filler' }, { motif: 'spokes' }, { motif: 'mesh' }, { motif: 'arches' }, { motif: 'clusters' },
    { motif: 'puffs', params: { pair: 1 } }, { motif: 'puffs', params: { pair: 2 } }, { motif: 'vstitch' },
    { motif: 'shells', params: { alt: 0, gap: 0 } }, { motif: 'shells', params: { alt: 0, gap: 2 } }, { motif: 'shells', params: { alt: 1 } },
    { motif: 'petals' }, { motif: 'fans', params: { form: 'scallop' } }, { motif: 'fans', params: { form: 'shell' } }, { motif: 'picot' },
  ];
  const motifs = MOTIF_ORDER.filter((m) => m !== 'centre');
  for (const centreStyle of ['solid', 'spoked']) {
    for (const p of preds) {
      it(`${centreStyle} centre → ${p.motif} ${JSON.stringify(p.params ?? {})} → each motif`, () => {
        for (const m of motifs) {
          for (const n of [5, 12]) {
            const spec: DoilySpec = { symmetry: n, rounds: [{ motif: 'centre', params: { style: centreStyle } }, { motif: 'mesh' }, p, { motif: m }] };
            const r = generateDoily(spec, THREAD);
            expectValid(r, spec, `${centreStyle} → ${p.motif} → ${m} n=${n}`);
            expect(r.rounds[r.rounds.length - 1].motif, `${p.motif} → ${m}`).toBe(m);
            expect(r.warnings.filter((w) => /skipped/.test(w))).toEqual([]);
            // a transition round appears exactly when the motif cannot work on what precedes it
            const prevKind = r.rounds[r.rounds.length - 2];
            if (!MOTIFS[m].accepts.includes('solid') && prevKind.spaces === 0) expect(prevKind.auto).toBe(true);
          }
        }
      }, 30_000);
    }
  }
});

describe('solver and predictor', () => {
  it('the predictor agrees with analyzeFlatness on the compiled pattern', () => {
    for (let seed = 1; seed <= 30; seed++) {
      const spec = randomSpec(seed, { rounds: [6, 12] }, { raw: true });
      const plan = planDoily(spec, THREAD);
      const r = generateDoily(spec, THREAD);
      const real = analyzeFlatness(r.pattern!.graph, THREAD);
      plan.planned.forEach((p, i) => {
        expect(real.rounds[i].e).toBeCloseTo(p.pred.e, 9);
        expect(real.rounds[i].eMin).toBeCloseTo(p.pred.eMin, 9);
        expect(real.rounds[i].r).toBeCloseTo(p.pred.r, 9);
        expect(real.rounds[i].class).toBe(p.pred.cls);
      });
    }
  });

  it('fixed parameters are honoured, auto ones solved', () => {
    const spec: DoilySpec = {
      symmetry: 12,
      rounds: [{ motif: 'centre', params: { st: 'dc', style: 'solid' } }, { motif: 'spokes', params: { ch: 2, st: 'dc' } }, { motif: 'shells', params: { size: 4, gap: 2 } }, { motif: 'mesh', params: { ch: 5 } }, { motif: 'picot' }],
    };
    const r = generateDoily(spec, THREAD);
    expectValid(r, spec, 'fixed');
    expect(r.rounds[1].params.ch).toBe(2);
    expect(r.rounds[1].text).toMatch(/ch 5 \(counts as dc, ch 2\)/);
    expect(r.rounds[2].text).toMatch(/\(2 dc, ch 2, 2 dc\)/);
    expect(r.rounds[3].text).toMatch(/ch 5\*/);
  });

  it('is deterministic and the same in every parameter set (proportional stitch sizes)', () => {
    for (const p of PRESETS) {
      const a = generateDoily(p.spec, THREAD), b = generateDoily(p.spec, THREAD);
      expect(a.text).toBe(b.text);
      const rounds = (t: string) => t.split('\n').filter((l) => l.startsWith('Rnd')).join('\n');
      for (const set of paramsFile.sets) expect(rounds(generateDoily(p.spec, set).text)).toBe(rounds(a.text));
    }
  });

  it('UK terms compile to the same graph as US terms', () => {
    for (const p of PRESETS) {
      const us = generateDoily({ ...p.spec, terms: 'US' }, THREAD);
      const uk = generateDoily({ ...p.spec, terms: 'UK' }, THREAD);
      expectValid(uk, p.spec, `${p.id} UK`);
      expect(uk.text).toMatch(/^terms: UK$/m);
      const strip = (g: GenerateResult) => g.pattern!.graph.nodes.map((nd) => `${nd.type}${nd.tag ?? ''}${nd.countsAs ?? ''}:${JSON.stringify(nd.into)}`).join(' ');
      expect(strip(uk)).toBe(strip(us));
    }
  });

  it('presets are valid and flat where meant to be', () => {
    for (const p of PRESETS) {
      const r = generateDoily(p.spec, THREAD);
      expectValid(r, p.spec, p.id);
      for (const x of r.rounds) expect(x.class, `${p.id} ${x.message}`).toBe(x.aim === 'flat' ? 'flat' : x.aim);
      expect(r.warnings, p.id).toEqual(r.warnings.filter((w) => /added before it/.test(w)));
    }
  });

  it('inserts a transition and explains it', () => {
    const r = generateDoily({ symmetry: 8, rounds: [{ motif: 'centre', params: { st: 'dc' } }, { motif: 'petals' }] }, THREAD);
    expect(r.rounds.map((x) => x.motif)).toEqual(['centre', 'mesh', 'petals']);
    expect(r.rounds[1].auto).toBe(true);
    expect(r.warnings.join(' ')).toMatch(/chain-loop mesh round was added/);
    const r2 = generateDoily({ symmetry: 8, rounds: [{ motif: 'mesh' }, { motif: 'accent' }] }, THREAD);
    expect(r2.rounds.map((x) => x.motif)).toEqual(['centre', 'mesh', 'filler', 'accent']);
  });

  it('stats are plausible', () => {
    const r = generateDoily(PRESETS[0].spec, THREAD);
    expect(r.stats.rounds).toBe(r.rounds.length);
    expect(r.stats.stitches).toBe(r.pattern!.graph.rounds.reduce((a, x) => a + x.stitchCount, 0));
    expect(r.stats.diameterMm).toBeGreaterThan(50);
    expect(r.stats.yarnM).toBeGreaterThan(1);
  });

  it('every motif has the metadata the UI needs', () => {
    for (const id of MOTIF_ORDER) {
      const m = MOTIFS[id as MotifId];
      expect(m.label.length).toBeGreaterThan(2);
      expect(m.blurb.length).toBeGreaterThan(10);
      for (const d of m.params) expect(d.values.length).toBeGreaterThan(0);
    }
  });
});

/**
 * npm run sim:corpus  [-- --check]
 *
 * Runs the app's spring sim on every data/corpus/*.cro (and, for reference, every fixture) with
 * the FAST tolerances the browser uses on large pieces, and writes docs/sim_corpus_report.md:
 * pattern → analytic final class vs sim class, A, W, converged. Review R1/R12/R22: the
 * disagreement between the count rule and the sim is documented with numbers, not hidden.
 * Nothing is tuned here (tau_flat and the tolerances come from spec/sim_config.json).
 *
 * --check: exit 1 if the committed report's table rows differ from a fresh run (timings ignored).
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { compilePattern } from '../src/core/notation/index';
import { FAST_TOLERANCES, surveyPattern, type SurveyRow } from '../src/core/sim/index';
import { simConfig } from '../src/core/params/index';

const root = fileURLToPath(new URL('../../', import.meta.url));
const out = root + 'docs/sim_corpus_report.md';
const check = process.argv.includes('--check');

const sets: { title: string; dir: string; prefix: string }[] = [
  { title: 'Corpus (`data/corpus`)', dir: root + 'data/corpus/', prefix: 'data/corpus/' },
  { title: 'Fixtures (`spec/fixtures`), for reference', dir: root + 'spec/fixtures/', prefix: 'spec/fixtures/' },
];

const f2 = (x: number) => x.toFixed(2);
const pct = (x: number) => `${x >= 0 ? '+' : '−'}${Math.abs(Math.round(x * 100))} %`;
const word = (r: SurveyRow) => `${r.analytic}${r.analyticSlackOnly ? ' (loose loops)' : ''}${r.analyticClosing ? ' (closed form)' : ''}`;

const lines: string[] = [];
const stats = { n: 0, agree: 0, unconverged: 0, flatN: 0, flatAgree: 0, totalMs: 0 };
const disagreements: string[] = [];
for (const s of sets) {
  const files = existsSync(s.dir) ? readdirSync(s.dir).filter((f) => f.endsWith('.cro')).sort() : [];
  lines.push('', `## ${s.title}`, '',
    '| pattern | nodes | count rule (final round) | e nominal | sim | A | W | agree | converged | unsettled rounds | time |',
    '|---|---:|---|---:|---|---:|---:|:---:|:---:|---:|---:|');
  for (const f of files) {
    const c = compilePattern(readFileSync(s.dir + f, 'utf8'));
    if (!c.pattern) { lines.push(`| ${f} | — | does not compile | | | | | | | | |`); continue; }
    const r = surveyPattern(c.pattern);
    const agree = r.analytic === r.sim;
    if (s.prefix === 'data/corpus/') {
      stats.n++; if (agree) stats.agree++; if (!r.converged) stats.unconverged++;
      if (r.analytic === 'flat') { stats.flatN++; if (agree) stats.flatAgree++; }
      if (!agree) disagreements.push(`${f.replace(/\.cro$/, '')} (count rule ${word(r)}, sim ${r.sim})`);
    }
    stats.totalMs += r.ms;
    lines.push(`| ${f.replace(/\.cro$/, '')} | ${r.nodes} | ${word(r)} | ${pct(r.analyticE)} | ${r.sim} | ${f2(r.A)} | ${f2(r.W)} | ${agree ? 'yes' : '**no**'} | ${r.converged ? 'yes' : '**no**'} | ${r.roundsUnsettled} | ${(r.ms / 1000).toFixed(1)} s |`);
    process.stderr.write(`${f}: ${r.analytic} vs ${r.sim} (A ${f2(r.A)} W ${f2(r.W)}, ${r.converged ? 'converged' : 'NOT converged'}, ${(r.ms / 1000).toFixed(1)} s)\n`);
  }
}

const head = [
  '# Sim vs count rule on the corpus',
  '',
  '_Generated by `cd app && npm run sim:corpus` (`app/scripts/sim-corpus.ts`). Do not edit by hand._',
  '',
  `The app's spring sim run on every corpus pattern with the **fast** tolerances (gtol ${FAST_TOLERANCES.gtolRound} per round, ${FAST_TOLERANCES.gtolFinal} final — what the browser uses for pieces over 600 stitches), compared with the analytic count rule. Shape classes from \`spec/sim_config.json\` (tau_flat ${simConfig.tau_flat}, count-rule tol ±${Math.round(simConfig.flatness.tol * 100)} %); nothing was retuned for this report.`,
  '',
  '**Headline.** ' +
    `On ${stats.n} corpus patterns the sim and the count rule agree on ${stats.agree} ` +
    `(${stats.flatAgree} of the ${stats.flatN} the count rule calls flat). ` +
    `${stats.unconverged} did not reach the fast tolerance within the iteration caps ("converged" below is relative to the fast tolerance; at the reference tolerances, review R12 found 5 of 16 hit the caps).` +
    (disagreements.length ? ` Disagreements: ${disagreements.join('; ')}.` : ''),
  '',
  'How to read it: the two models have different sensitivity. The sim reacts to mismatches of a few percent, the count rule tolerates ±10 %, and the sim has no stuffing, gravity or self-collision. A strongly ruffled short piece can score A ≥ W and be classed a cup (review R1). The 3D view therefore presents its class as a tendency, not a verdict, and marks unconverged or fast solves as approximate. "loose loops": the count rule calls the round flat only because its chain loops may sag or stretch (flatness.md). "closed form": a round closes the shape (amigurumi-style); the unstuffed sim relaxes it like an empty bag.',
  '',
  'Timings are from the machine that generated the file and vary with load.',
];
const text = [...head, ...lines, ''].join('\n');
const strip = (t: string) => t.split('\n').filter((l) => l.startsWith('| ') && !l.startsWith('| pattern')).map((l) => l.replace(/\| [\d.]+ s \|$/, '|')).join('\n');
if (check) {
  const old = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (strip(old) !== strip(text)) { console.error('docs/sim_corpus_report.md is out of date: run npm run sim:corpus'); process.exit(1); }
  console.log('docs/sim_corpus_report.md is current');
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out} (${(stats.totalMs / 1000).toFixed(0)} s of solving)`);
}
